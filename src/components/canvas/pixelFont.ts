// Normalize Vietnamese accents for bitmap rendering fallback
function stripAccents(str: string): string {
  return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

export interface TextPixel {
  id: string;
  x: number;
  y: number;
  size: number;
  isHit: boolean;
  hitTime?: number;
  char: string;
}

/**
 * Builds the positioned raster pixel array for a line of text centered at (centerX, centerY).
 */
export function rasterizeText(
  text: string,
  centerX: number,
  centerY: number,
  pixelSize: number,
  gap: number = 1,
  charSpacing: number = 2
): TextPixel[] {
  const pixels: TextPixel[] = [];
  const normalized = stripAccents(text).toUpperCase();
  const chars = normalized.split('');
  
  // Calculate total width of text
  let totalWidth = 0;
  for (let i = 0; i < chars.length; i++) {
    const char = chars[i];
    const matrix = PIXEL_FONT_5X5[char] || PIXEL_FONT_5X5[' '];
    const cols = matrix[0].length;
    totalWidth += cols * (pixelSize + gap);
    if (i < chars.length - 1) {
      totalWidth += charSpacing * (pixelSize + gap);
    }
  }

  const height = 5 * (pixelSize + gap);
  let currentX = centerX - totalWidth / 2;
  const startY = centerY - height / 2;

  chars.forEach((char, charIdx) => {
    const matrix = PIXEL_FONT_5X5[char] || PIXEL_FONT_5X5[' '];
    const rows = matrix.length;
    const cols = matrix[0].length;

    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        if (matrix[r][c] === 1) {
          const px = currentX + c * (pixelSize + gap);
          const py = startY + r * (pixelSize + gap);
          pixels.push({
            id: `${charIdx}-${char}-${r}-${c}`,
            x: px,
            y: py,
            size: pixelSize,
            isHit: false,
            char
          });
        }
      }
    }

    currentX += cols * (pixelSize + gap) + charSpacing * (pixelSize + gap);
  });

  return pixels;
}
